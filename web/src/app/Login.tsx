import { ArrowRight, Eye, EyeOff, KeyRound } from 'lucide-react';
import { useEffect, useEffectEvent, useId, useRef, useState, type SubmitEvent } from 'react';
import { useLocation } from 'wouter';
import { Button, IconButton } from '../design/components/Button';
import { CommandLine } from '../design/components/CommandLine';
import { InlineCode } from '../design/components/InlineCode';
import { ApiError, api, problemOf } from '../lib/api';
import { sentence } from '../lib/gpu';
import { hasSignInToken, onSignInLink, takeSignInToken } from '../lib/signInLink';
import { useConnection } from '../store/connection';
import { retryConnection, useAuthInfo } from '../store/session';
import { ConnectionIndicator } from './ConnectionIndicator';
import './Login.css';

type LoginError = { title: string; detail: string } | null;

export function loginErrorCopy(e: unknown): NonNullable<LoginError> {
  if (e instanceof ApiError && (e.kind === 'unauthorized' || e.status === 403)) {
    return {
      title: 'That token wasn’t accepted.',
      detail: 'Copy `token` from `/etc/sparkline/console.toml` on the console host and try again.',
    };
  }
  if (e instanceof ApiError && e.kind === 'client') {
    // The console answers with its own {problem}: say that, never the JSON it came in.
    const p = problemOf(e, 'sign in');
    return { title: sentence(p.message), detail: [p.cause, p.fix].filter(Boolean).map(sentence).join(' ') };
  }
  return {
    title: 'Can’t reach Sparkline.',
    detail: 'Check that it is running: `systemctl status sparkline`, or start `sparkline --demo`.',
  };
}

export const TOKEN_COMMAND = 'sudo grep ^token /etc/sparkline/console.toml';

function WhereIsTheToken({ id }: { id?: string }) {
  return (
    <div className="login__where" id={id}>
      <p>
        <strong>The token is on the console host.</strong> It is <code>token</code> in <code>/etc/sparkline/console.toml</code>, unless
        you set <code>SPARKLINE_TOKEN</code> yourself. Run in a terminal, <code>install.sh</code> prints it too, with a link that signs
        you in without typing. This prints the one in the file:
      </p>
      <CommandLine text={TOKEN_COMMAND} compact />
    </div>
  );
}

export function Login() {
  const [, navigate] = useLocation();
  const conn = useConnection((s) => s.status);
  const [token, setToken] = useState('');
  const [reveal, setReveal] = useState(false);
  // Opened from a sign-in link: the page starts signing in, with nothing to type.
  const [signingIn, setSigningIn] = useState<'link' | 'typed' | null>(() => (hasSignInToken() ? 'link' : null));
  const busy = signingIn !== null;
  const firstRunNow = useAuthInfo((s) => s.firstRun);
  // What the page was when a link first signed in on it. /auth/me can answer meanwhile and the link can be wrong:
  // the title stays for the rest of the visit, and the page under "Signing in…" until that ends.
  const [atLink, setAtLink] = useState<boolean | null>(() => (signingIn === 'link' ? firstRunNow : null));
  const welcome = atLink ?? firstRunNow;
  const firstRun = signingIn === 'link' ? welcome : firstRunNow;
  const [error, setError] = useState<LoginError>(null);
  const field = useRef<HTMLInputElement>(null);
  const fieldId = useId();
  const errorId = useId();
  const hintId = useId();
  const whereId = useId();

  const exchange = (secret: string) =>
    void api.login(secret)
      .then(
        () => {
          retryConnection();
          navigate('/', { replace: true });
        },
        (err: unknown) => {
          setError(loginErrorCopy(err));
          // A clicked "Sign in" loses focus when it is disabled for the request: the next thing to do is retype.
          field.current?.focus();
        },
      )
      .finally(() => { setSigningIn(null); });
  const signIn = (how: 'link' | 'typed', secret: string) => {
    setSigningIn(how);
    setError(null);
    exchange(secret);
  };

  // On arrival the page already shows "Signing in…" (the state above starts that way).
  const arrivedByLink = useEffectEvent(() => {
    const linked = takeSignInToken();
    if (linked) exchange(linked);
  });
  // The link opened in this tab while the sign-in page was already showing.
  const linkOpenedHere = useEffectEvent(() => {
    const later = takeSignInToken();
    if (!later) return;
    setAtLink((was) => was ?? firstRunNow);
    signIn('link', later);
  });
  useEffect(() => {
    arrivedByLink();
    return onSignInLink(() => { linkOpenedHere(); });
  }, []);

  const submit = (e: SubmitEvent) => {
    e.preventDefault();
    if (!token.trim()) {
      setError({ title: 'Enter your console token.', detail: 'It is the `token` value in `/etc/sparkline/console.toml`, generated by `install.sh`.' });
      return;
    }
    signIn('typed', token.trim());
  };

  return (
    <main className="login" id="main">
      <div className={`login__card material-regular${firstRun ? ' login__card--first' : ''}`}>
        <div className="login__mark" aria-hidden="true">
          <svg viewBox="0 0 32 32" width="44" height="44"><rect width="32" height="32" rx="9" fill="var(--accent-fill)" /><path d="M7 19.5h4l2.5-7 4 12 3-9 1.5 4H25" fill="none" stroke="#fff" strokeWidth="2.4" strokeLinecap="round" strokeLinejoin="round" /></svg>
        </div>
        <h1 className="login__title">{welcome ? 'Welcome to Sparkline' : 'Sign in to Sparkline'}</h1>
        <p className="login__lead">
          {signingIn === 'link' ? 'Signing in with your link.' : firstRun ? 'This console is new. Sign in with its token and your nodes are on the next screen.' : 'Enter the console token for this cluster.'}
        </p>

        <form className="login__form" onSubmit={submit} noValidate>
          <label htmlFor={fieldId} className="login__label">Console token</label>
          <div className="login__field">
            <KeyRound className="login__field-icon" aria-hidden="true" />
            <input
              id={fieldId}
              ref={field}
              className="input login__input"
              type={reveal ? 'text' : 'password'}
              autoComplete="current-password"
              spellCheck={false}
              autoCapitalize="off"
              value={token}
              onChange={(e) => { setToken(e.target.value); if (error) setError(null); }}
              aria-invalid={error ? true : undefined}
              aria-describedby={error ? errorId : firstRun ? `${whereId} ${hintId}` : hintId}
              // The only field on a dedicated sign-in page.
              // eslint-disable-next-line jsx-a11y/no-autofocus
              autoFocus
            />
            <IconButton
              className="login__reveal"
              size="sm"
              aria-label={reveal ? 'Hide token' : 'Show token'}
              aria-pressed={reveal}
              icon={reveal ? <EyeOff /> : <Eye />}
              onClick={() => { setReveal((v) => !v); }}
            />
          </div>
          {firstRun ? <WhereIsTheToken id={whereId} /> : null}
          <div className="login__message" aria-live="polite">
            {error ? (
              <p id={errorId} className="login__error">
                <strong>{error.title}</strong> <InlineCode text={error.detail} />
              </p>
            ) : (
              <p id={hintId} className="login__hint">
                Exchanged for a secure session cookie. The token itself isn’t stored in this browser.
              </p>
            )}
          </div>
          <Button type="submit" variant="primary" size="lg" className="login__submit" disabled={busy}>
            {busy ? 'Signing in…' : 'Sign in'}
            {busy ? null : <ArrowRight aria-hidden="true" className="login__arrow" />}
          </Button>
          {firstRun ? null : (
            <details className="login__more">
              <summary>Where is the token?</summary>
              <WhereIsTheToken />
            </details>
          )}
        </form>
      </div>
      {conn === 'reconnecting' || conn === 'offline' ? (
        <div className="login__conn">
          <ConnectionIndicator />
        </div>
      ) : (
        <p className="login__foot">Sparkline · DGX Spark cluster telemetry</p>
      )}
    </main>
  );
}
